def pick(templates, idx, slot):
    return templates[(idx * 3 + slot) % len(templates)]


def get_noun_forms(lemma, kyn, idx):
    """Return (nef_form, thol_form, thag_form, eig_form, sentences_dict) or None."""
    try:
        _, matches = b.lookup(lemma)
    except Exception:
        return None
    noun_matches = [m for m in matches if m.ofl == kyn]
    if not noun_matches:
        return None
    # prefer the match where the lemma itself is NFET
    nfet_match = next((m for m in noun_matches if m.mark == "NFET"), None)
    target = nfet_match or noun_matches[0]
    bin_id = target.bin_id
    try:
        all_forms = b.lookup_id(bin_id)
    except Exception:
        return None
    nf  = next((f.bmynd for f in all_forms if f.mark == "NFET"),  None)
    tf  = next((f.bmynd for f in all_forms if f.mark == "ÞFET"),  None)
    tgf = next((f.bmynd for f in all_forms if f.mark == "ÞGFET"), None)
    ef  = next((f.bmynd for f in all_forms if f.mark == "EFET"),  None)
    if not all([nf, tf, tgf, ef]):
        return None
    return nf, tf, tgf, ef


def get_verb_forms(lemma, idx):
    """Return (present, past, imperative, subj_past) or None."""
    try:
        _, matches = b.lookup(lemma)
    except Exception:
        return None
    so_matches = [m for m in matches if m.ofl == "so"]
    if not so_matches:
        return None
    # prefer generic active (alm/hluti), take first so
    target = next((m for m in so_matches if "alm" in str(m)), so_matches[0])
    bin_id = target.bin_id
    try:
        all_forms = b.lookup_id(bin_id)
    except Exception:
        return None
    def get(mark):
        return next((f.bmynd for f in all_forms if f.mark == mark), None)
    present  = get("GM-FH-NT-3P-ET")
    past     = get("GM-FH-ÞT-3P-ET")
    imp      = get("GM-BH-ET")
    subj_p   = get("GM-VH-ÞT-3P-ET")
    if not all([present, past, imp, subj_p]):
        return None
    return present, past, imp, subj_p


def build_entry(lemma, translation, kyn, category, idx):
    if kyn == "so":
        forms = get_verb_forms(lemma, idx)
        if not forms:
            return None
        present, past, imp, subj_p = forms
        ts = TMPL
        return {
            "base": f"að {lemma}",
            "translation": translation,
            "category": category,
            "gender": "-",
            "plurality": "-",
            "article": "-",
            "nefnifall":  {"word": present, "sentence": pick(ts["nef_so"], idx, 0)},
            "tholfall":   {"word": past,    "sentence": pick(ts["thol_so"], idx, 1)},
            "thagufall":  {"word": imp,     "sentence": pick(ts["thag_so"], idx, 2)},
            "eignarfall": {"word": subj_p,  "sentence": pick(ts["eig_so"], idx, 3)},
        }
    else:
        forms = get_noun_forms(lemma, kyn, idx)
        if not forms:
            return None
        nf, tf, tgf, ef = forms
        # pick template set
        cat_key = category.lower()
        if cat_key == "dýr":
            tnf, tth, ttg, tef = TMPL["nef_dyr"], TMPL["thol_dyr"], TMPL["thag_dyr"], TMPL["eig_dyr"]
        elif cat_key == "matur":
            tnf, tth, ttg, tef = TMPL["nef_matur"], TMPL["thol_matur"], TMPL["thag_matur"], TMPL["eig_matur"]
        elif cat_key == "náttúra":
            tnf, tth, ttg, tef = TMPL["nef_nattura"], TMPL["thol_nattura"], TMPL["thag_nattura"], TMPL["eig_nattura"]
        elif cat_key == "líkami":
            tnf, tth, ttg, tef = TMPL["nef_likam"], TMPL["thol_likam"], TMPL["thag_likam"], TMPL["eig_likam"]
        elif cat_key == "klæði":
            tnf, tth, ttg, tef = TMPL["nef_kladi"], TMPL["thol_kladi"], TMPL["thag_kladi"], TMPL["eig_kladi"]
        else:
            tnf, tth, ttg, tef = TMPL["nef"], TMPL["thol"], TMPL["thag"], TMPL["eig"]
        plural_s = "eintala"
        article_s = "án greinis"
        return {
            "base": lemma,
            "translation": translation,
            "category": category,
            "gender": kyn,
            "plurality": plural_s,
            "article": article_s,
            "nefnifall":  {"word": nf,  "sentence": pick(tnf, idx, 0)},
            "tholfall":   {"word": tf,  "sentence": pick(tth, idx, 1)},
            "thagufall":  {"word": tgf, "sentence": pick(ttg, idx, 2)},
            "eignarfall": {"word": ef,  "sentence": pick(tef, idx, 3)},
        }


