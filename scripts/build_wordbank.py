for _extra in (EXTRA, EXTRA2, EXTRA3, EXTRA4):
    for _cat, _entries in _extra.items():
        if _cat in WORDS:
            WORDS[_cat].extend(_entries)
        else:
            WORDS[_cat] = _entries


# ──────────────────────────────────────────────────────────────────────────────
# MAIN
# ──────────────────────────────────────────────────────────────────────────────

def main():
    categories = list(WORDS.keys())
    bank = {cat: [] for cat in categories}
    total = 0
    skipped = 0

    for cat, entries in WORDS.items():
        seen_bases = set()
        for idx, (lemma, translation, kyn) in enumerate(entries):
            key = (lemma, kyn)
            if key in seen_bases:
                continue
            seen_bases.add(key)

            entry = build_entry(lemma, translation, kyn, cat, idx)
            if entry is None:
                skipped += 1
                print(f"  SKIP  {lemma:25s}  ({kyn})  [{cat}]", file=sys.stderr)
                continue
            bank[cat].append(entry)
            total += 1

        print(f"  {cat:12s}: {len(bank[cat])} words", file=sys.stderr)

    print(f"\nTotal: {total} entries, {skipped} skipped", file=sys.stderr)

    out = {
        "categories": categories,
        "words": bank,
    }

    # write output
    script_dir = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(script_dir, "..", "Refur", "words.json")
    out_path = os.path.normpath(out_path)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    print(f"\nWrote {out_path}", file=sys.stderr)


if __name__ == "__main__":
    main()
